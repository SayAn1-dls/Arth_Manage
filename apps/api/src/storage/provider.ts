import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import { dirname, resolve, sep } from 'node:path';

/**
 * File storage behind an interface (DECISIONS D-13). The only adapter today writes to a private directory
 * on local disk, so this is platform-local storage, not cloud storage; an object-storage adapter can
 * implement the same two methods later without touching callers.
 */
export interface StorageProvider {
  put(key: string, bytes: Buffer): Promise<void>;
  get(key: string): Promise<Buffer>;
  /** Proves the store accepts, returns and removes an object. Used by the health check and at start-up. */
  check(): Promise<void>;
}

export class LocalDiskStorage implements StorageProvider {
  private readonly root: string;
  constructor(root: string) {
    this.root = resolve(root);
  }

  /** Keys are generated by the server, but resolve defensively so a bad key can never escape the root. */
  private pathFor(key: string): string {
    const full = resolve(this.root, key);
    if (!full.startsWith(this.root + sep)) throw new Error('Invalid storage key');
    return full;
  }

  async put(key: string, bytes: Buffer): Promise<void> {
    const path = this.pathFor(key);
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, bytes, { flag: 'wx' }); // never overwrite an existing object
  }

  async get(key: string): Promise<Buffer> {
    return readFile(this.pathFor(key));
  }

  async check(): Promise<void> {
    const key = `.health/${randomUUID()}`;
    const probe = Buffer.from('ok');
    await this.put(key, probe);
    const back = await this.get(key);
    await rm(this.pathFor(key), { force: true });
    if (!back.equals(probe)) throw new Error('Storage returned different bytes than were written');
  }
}
